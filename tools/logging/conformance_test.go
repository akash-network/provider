package logging

import (
	"context"
	"encoding/json"
	"os"
	"testing"

	"github.com/spf13/cobra"
	"github.com/stretchr/testify/require"
	"go.uber.org/zap/zapcore"
)

// conformanceFixture is testdata/conformance.json. The attestation sidecar, a separate module
// with its own copy of this package (sidecar/attestation/internal/logging), runs the same file
// against its implementation, so a change made to one copy only fails the other's tests.
type conformanceFixture struct {
	Defaults struct {
		Level     string `json:"level"`
		Format    string `json:"format"`
		Color     bool   `json:"color"`
		Timestamp string `json:"timestamp"`
		Trace     bool   `json:"trace"`
	} `json:"defaults"`
	Cases []struct {
		Name string `json:"name"`
		In   struct {
			Level     string `json:"level"`
			Format    string `json:"format"`
			Color     bool   `json:"color"`
			Timestamp string `json:"timestamp"`
			Trace     bool   `json:"trace"`
		} `json:"in"`
		// Want is nil when the input must be rejected.
		Want *conformanceWant `json:"want"`
		// Env holds the variables generated by Config.Env, without prefix; required with Want. The
		// provider passes them to the hardware discovery pods (AP_) and the attestation sidecar
		// (ATTESTATION_), which must resolve Want from them.
		Env map[string]string `json:"env"`
	} `json:"cases"`
}

type conformanceWant struct {
	LevelSpec string            `json:"level_spec"`
	Level     string            `json:"level"`
	Modules   map[string]string `json:"modules"`
	Format    string            `json:"format"`
	Color     bool              `json:"color"`
	Timestamp string            `json:"timestamp"`
	Trace     bool              `json:"trace"`
}

func loadConformanceFixture(t *testing.T) conformanceFixture {
	t.Helper()

	data, err := os.ReadFile("testdata/conformance.json")
	require.NoError(t, err)

	var fixture conformanceFixture
	require.NoError(t, json.Unmarshal(data, &fixture))
	require.NotEmpty(t, fixture.Cases)

	return fixture
}

// levelName is the fixture's name of a resolved level: zap's name, or "disabled"
// for a level above every zap level.
func levelName(lvl zapcore.Level) string {
	if lvl > zapcore.FatalLevel {
		return "disabled"
	}

	return lvl.String()
}

func requireConformance(t *testing.T, want conformanceWant, cfg Config) {
	t.Helper()

	modules := map[string]string{}
	for module, lvl := range cfg.Modules {
		modules[module] = levelName(lvl)
	}

	wantModules := want.Modules
	if wantModules == nil {
		wantModules = map[string]string{}
	}

	require.Equal(t, want.LevelSpec, cfg.LevelSpec)
	require.Equal(t, want.Level, levelName(cfg.Level))
	require.Equal(t, wantModules, modules)
	require.Equal(t, want.Format, cfg.Format)
	require.Equal(t, want.Color, cfg.Color)
	require.Equal(t, want.Timestamp, cfg.Timestamp)
	require.Equal(t, want.Trace, cfg.Trace)
}

func TestDefaultsConformance(t *testing.T) {
	want := loadConformanceFixture(t).Defaults

	require.Equal(t, want.Level, DefaultLevel)
	require.Equal(t, want.Format, DefaultFormat)
	require.Equal(t, want.Color, DefaultColor)
	require.Equal(t, want.Timestamp, DefaultTimestamp)
	require.Equal(t, want.Trace, DefaultTrace)
}

func TestParseConfigConformance(t *testing.T) {
	for _, tc := range loadConformanceFixture(t).Cases {
		t.Run(tc.Name, func(t *testing.T) {
			cfg, err := ParseConfig(tc.In.Level, tc.In.Format, tc.In.Color, tc.In.Timestamp, tc.In.Trace)
			if tc.Want == nil {
				require.Error(t, err)
				return
			}
			require.NoError(t, err)
			requireConformance(t, *tc.Want, cfg)
			require.NotNil(t, tc.Env, "accepted cases must list the variables Config.Env generates")

			env := map[string]string{}
			for _, e := range cfg.Env("") {
				env[e.Name] = e.Value
			}
			require.Equal(t, tc.Env, env)

			// a provider-services process started with the AP_ variables (hardware discovery pod)
			// resolves the same configuration
			resetViper(t)
			clearLogEnv(t)
			for name, val := range tc.Env {
				t.Setenv("AP_"+name, val)
			}

			var got Config
			cmd := &cobra.Command{
				Use: "probe",
				RunE: func(cmd *cobra.Command, _ []string) error {
					if _, err := Setup(cmd, "AP"); err != nil {
						return err
					}
					got, _ = ConfigFromCtx(cmd.Context())
					return nil
				},
			}
			AddFlags(cmd.PersistentFlags())
			cmd.PersistentFlags().Bool(FlagTrace, DefaultTrace, "")
			cmd.SetArgs([]string{})

			require.NoError(t, cmd.ExecuteContext(context.Background()))
			requireConformance(t, *tc.Want, got)
		})
	}
}
